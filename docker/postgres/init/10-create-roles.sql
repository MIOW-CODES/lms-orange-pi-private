\set ON_ERROR_STOP on
\getenv migrator_password POSTGRES_MIGRATOR_PASSWORD
\getenv app_password POSTGRES_APP_PASSWORD

CREATE ROLE miow_migrator
  LOGIN
  PASSWORD :'migrator_password'
  NOSUPERUSER
  NOCREATEDB
  NOCREATEROLE
  NOREPLICATION
  NOBYPASSRLS
  CONNECTION LIMIT 2;

CREATE ROLE miow_app
  LOGIN
  PASSWORD :'app_password'
  NOSUPERUSER
  NOCREATEDB
  NOCREATEROLE
  NOREPLICATION
  NOBYPASSRLS
  CONNECTION LIMIT 8;

REVOKE ALL ON DATABASE miow FROM PUBLIC;
GRANT CONNECT ON DATABASE miow TO miow_migrator, miow_app;
ALTER DATABASE miow OWNER TO miow_migrator;

ALTER SCHEMA public OWNER TO miow_migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO miow_app;

CREATE SCHEMA private AUTHORIZATION miow_migrator;
REVOKE ALL ON SCHEMA private FROM PUBLIC, miow_app;

ALTER DEFAULT PRIVILEGES FOR ROLE miow_migrator
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
